"""Text data for the generative brain: download → train a 32k BPE tokenizer → token ids on disk (uint16).

Sources (all human-written, no text generated by other AI models):
  * Arabic Wikipedia (full) and part of English Wikipedia, via the `datasets` library
  * NEXUS's own knowledge library (data/kb) and corpus (data/corpus) when present
`--local` uses only the files in data/ so the pipeline can be tested on a laptop.
"""
import gzip
import json
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
SPECIAL = ["<|endoftext|>", "<|user|>", "<|assistant|>", "<|pad|>"]
_CLEAN = re.compile(r"\s+")


def local_texts():
    kb = ROOT / "data" / "kb" / "kb.jsonl.gz"
    if kb.exists():
        with gzip.open(kb, "rt", encoding="utf-8") as f:
            for line in f:
                a = json.loads(line)
                yield "\n".join(p for _, ps in a["sections"] for p in ps)
    for name in ("ar.txt", "en.txt"):
        path = ROOT / "data" / "corpus" / name
        if path.exists():
            yield from path.read_text(encoding="utf-8").split("\n")


def wiki_texts(english_share: float = 0.25):
    """Every Arabic article, then English articles up to `english_share` of the Arabic count."""
    from datasets import load_dataset
    ar = load_dataset("wikimedia/wikipedia", "20231101.ar", split="train", streaming=True)
    count = 0
    for row in ar:
        count += 1
        yield row["text"]
    en = load_dataset("wikimedia/wikipedia", "20231101.en", split="train", streaming=True)
    for i, row in enumerate(en):
        if i >= count * english_share:
            break
        yield row["text"]


def documents(local: bool):
    yield from local_texts()
    if not local:
        yield from wiki_texts()


def train_tokenizer(texts, out: Path, vocab: int = 32000):
    """Byte-level BPE: any Arabic, English, emoji or code is representable, nothing is <unk>."""
    from tokenizers import Tokenizer, decoders, models, pre_tokenizers, trainers
    tok = Tokenizer(models.BPE())
    tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    tok.decoder = decoders.ByteLevel()
    trainer = trainers.BpeTrainer(vocab_size=vocab, special_tokens=SPECIAL, min_frequency=2,
                                  initial_alphabet=pre_tokenizers.ByteLevel.alphabet())
    tok.train_from_iterator(texts, trainer=trainer)
    tok.save(str(out))
    return tok


def build(out_dir: Path, local: bool = False, tokenizer_docs: int = 300_000, val_every: int = 200) -> dict:
    """Write tokenizer.json, train.bin and val.bin into out_dir (skips work that is already done)."""
    from tokenizers import Tokenizer
    out_dir.mkdir(parents=True, exist_ok=True)
    tok_path = out_dir / "tokenizer.json"
    if not tok_path.exists():
        sample = (_CLEAN.sub(" ", t) for i, t in enumerate(documents(local)) if i < tokenizer_docs)
        train_tokenizer(sample, tok_path)
    tok = Tokenizer.from_file(str(tok_path))
    eot = tok.token_to_id("<|endoftext|>")
    if not (out_dir / "train.bin").exists():
        with open(out_dir / "train.bin", "wb") as tr, open(out_dir / "val.bin", "wb") as va:
            batch, n = [], 0
            for text in documents(local):
                text = text.strip()
                if len(text) < 40:
                    continue
                batch.append(text)
                if len(batch) == 1000:
                    n = _flush(tok, batch, eot, tr, va, n, val_every)
                    batch = []
            _flush(tok, batch, eot, tr, va, n, val_every)
    sizes = {s: (out_dir / f"{s}.bin").stat().st_size // 2 for s in ("train", "val")}
    print(f"tokens: train {sizes['train']:,}  val {sizes['val']:,}  vocab {tok.get_vocab_size()}")
    return {"vocab": tok.get_vocab_size(), **sizes}


def _flush(tok, batch, eot, tr, va, n, val_every) -> int:
    for enc in tok.encode_batch(batch):
        ids = np.array(enc.ids + [eot], dtype=np.uint16)
        (va if n % val_every == 0 else tr).write(ids.tobytes())  # every 200th document is held out
        n += 1
    return n
